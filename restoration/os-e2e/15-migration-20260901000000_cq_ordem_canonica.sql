-- =====================================================================
-- FASE 6 — Determinismo canônico do "último CQ" (substitui o desempate
-- por `ctid`, que é endereço físico e muda em UPDATE/VACUUM FULL/rewrite).
--
-- Estratégia:
--   1. `controle_qualidade.seq` — identidade bigint monotônica e persistente.
--   2. Backfill determinístico conservador por (created_at, ctid) atual:
--      preserva a ordem observada hoje, sem recalcular histórico de negócio.
--      LIMITAÇÃO: registros históricos com created_at empatado herdam a
--      ordem física vigente no momento do backfill (melhor informação
--      disponível); a partir daqui a ordem é estável.
--   3. Regra canônica única: ORDER BY created_at DESC, seq DESC.
--   4. Todos os consumidores do "último CQ" passam a usar a mesma regra.
--
-- Guard fail-closed: marker EXATO STAGING/ikaauvsflpmamgxmkhoq
-- (public._fiscal_staging_marker) + recusa explícita de produção.
-- =====================================================================

DO $guard$
DECLARE
  v_ref text;
BEGIN
  IF to_regclass('public._fiscal_staging_marker') IS NULL THEN
    RAISE EXCEPTION 'ABORT_AMBIENTE: marker de ambiente ausente; alvo nao comprovado.';
  END IF;

  SELECT m.project_ref INTO v_ref
    FROM public._fiscal_staging_marker m
   WHERE m.marker = 'STAGING'
   LIMIT 1;

  IF v_ref = 'navfzbwgwzruipouyfnk' THEN
    RAISE EXCEPTION 'ABORT_PRODUCAO: migration proibida em navfzbwgwzruipouyfnk';
  END IF;

  IF v_ref IS DISTINCT FROM 'ikaauvsflpmamgxmkhoq' THEN
    RAISE EXCEPTION 'ABORT_AMBIENTE: alvo % nao e o staging autorizado ikaauvsflpmamgxmkhoq', coalesce(v_ref, '<nulo>');
  END IF;
END;
$guard$;

-- ---------------------------------------------------------------------
-- 1. Coluna monotônica persistente
-- ---------------------------------------------------------------------
ALTER TABLE public.controle_qualidade
  ADD COLUMN IF NOT EXISTS seq bigint;

DO $backfill$
DECLARE
  v_max bigint;
BEGIN
  -- Backfill conservador: ordem observada hoje (created_at, ctid).
  WITH ordenado AS (
    SELECT id, row_number() OVER (ORDER BY created_at, ctid) AS rn
      FROM public.controle_qualidade
     WHERE seq IS NULL
  )
  UPDATE public.controle_qualidade cq
     SET seq = o.rn
    FROM ordenado o
   WHERE cq.id = o.id;

  SELECT coalesce(max(seq), 0) INTO v_max FROM public.controle_qualidade;

  EXECUTE 'ALTER TABLE public.controle_qualidade ALTER COLUMN seq SET NOT NULL';

  IF NOT EXISTS (
    SELECT 1 FROM pg_attribute a
     WHERE a.attrelid = 'public.controle_qualidade'::regclass
       AND a.attname = 'seq'
       AND a.attidentity <> ''
  ) THEN
    EXECUTE format(
      'ALTER TABLE public.controle_qualidade ALTER COLUMN seq ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)',
      v_max + 1
    );
  END IF;
END;
$backfill$;

CREATE UNIQUE INDEX IF NOT EXISTS ux_controle_qualidade_seq
  ON public.controle_qualidade (seq);

CREATE INDEX IF NOT EXISTS ix_controle_qualidade_lote_ordem
  ON public.controle_qualidade (lote_id, created_at DESC, seq DESC);

-- ---------------------------------------------------------------------
-- 2. Função canônica de leitura do último CQ
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_cq_ultimo_resultado(p_lote_id uuid)
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $$
  SELECT cq.resultado::text
    FROM public.controle_qualidade cq
   WHERE cq.lote_id = p_lote_id
   ORDER BY cq.created_at DESC, cq.seq DESC
   LIMIT 1;
$$;

REVOKE ALL ON FUNCTION public.fn_cq_ultimo_resultado(uuid) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.fn_cq_ultimo_resultado(uuid) FROM anon;
GRANT EXECUTE ON FUNCTION public.fn_cq_ultimo_resultado(uuid) TO authenticated, service_role;

-- ---------------------------------------------------------------------
-- 3. Consumidores: substituição textual determinística do desempate.
--    Não reescreve regra de negócio, apenas o critério de ordenação.
-- ---------------------------------------------------------------------
DO $patch$
DECLARE
  r record;
  v_def text;
  v_novo text;
  v_patched int := 0;
BEGIN
  FOR r IN
    SELECT p.oid, p.proname, pg_get_functiondef(p.oid) AS def
      FROM pg_proc p
      JOIN pg_namespace n ON n.oid = p.pronamespace
     WHERE n.nspname = 'public'
       AND p.proname IN (
         '_rpc_avancar_esteira_laboratorio_internal',
         'rpc_cockpit_registrar_envase_v1',
         'fn_validate_envase_cq',
         'fn_avancar_etapa_esteira'
       )
  LOOP
    v_def := r.def;
    v_novo := replace(v_def, 'created_at DESC, ctid DESC', 'created_at DESC, seq DESC');
    -- motor legado sem desempate algum
    v_novo := replace(
      v_novo,
      'FROM controle_qualidade WHERE lote_id = v_lote_id ORDER BY created_at DESC LIMIT 1',
      'FROM controle_qualidade WHERE lote_id = v_lote_id ORDER BY created_at DESC, seq DESC LIMIT 1'
    );
    IF v_novo IS DISTINCT FROM v_def THEN
      EXECUTE v_novo;
      v_patched := v_patched + 1;
    END IF;
  END LOOP;

  IF v_patched < 4 THEN
    RAISE EXCEPTION 'CQ_PATCH_INCOMPLETO: % de 4 funcoes atualizadas', v_patched;
  END IF;
END;
$patch$;

-- ---------------------------------------------------------------------
-- 4. Postcheck fail-closed: nenhum consumidor pode continuar com ctid.
-- ---------------------------------------------------------------------
DO $postcheck$
DECLARE
  v_ctid int;
  v_sem_seq int;
BEGIN
  SELECT count(*) INTO v_ctid
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
   WHERE n.nspname = 'public'
     AND pg_get_functiondef(p.oid) ~ 'controle_qualidade'
     AND pg_get_functiondef(p.oid) ~ 'ctid';
  IF v_ctid > 0 THEN
    RAISE EXCEPTION 'CQ_CTID_REMANESCENTE: % funcoes ainda usam ctid', v_ctid;
  END IF;

  SELECT count(*) INTO v_sem_seq FROM public.controle_qualidade WHERE seq IS NULL;
  IF v_sem_seq > 0 THEN
    RAISE EXCEPTION 'CQ_SEQ_NULA: % registros sem seq', v_sem_seq;
  END IF;
END;
$postcheck$;
